sentence = input("Enter a sentence: ")

print("Original : ", sentence) # original
print("LowerCae : ", sentence.lower()) #lowercase using .lower()
print("Uppercase : ", sentence.upper()) #uppercase using .upper()
print("Length : ", len(sentence)) #finding the length of the string using len()
print("Split words : ", sentence.split()) #seprating words using .split()


